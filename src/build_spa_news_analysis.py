    w.writerow(["브랜드", "출처", "수집 번호", "날짜", "제목", "요약", "원문 링크", "함께 수집된 브랜드", "같은 이슈 보도 수"])
    for r in rows:
        w.writerow([r["브랜드"], r["출처"], r["수집 번호"], r["날짜"], r["제목"], r["요약"], r["원문 링크"],
                    ", ".join(b for b in M.ORDER if b in r["also"]), r["count"]])
